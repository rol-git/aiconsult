"""Грубая граница Тюменской области — bbox + полигональный тест.

Для проверки `is_in_tyumen` нам не нужна сверхточная граница (точность
до 10 км приемлема). Используем bbox + проверку, что регион — Тюменская
область, по координатам.
"""

from __future__ import annotations

# Грубый bbox Тюм. области (без ХМАО/ЯНАО):
#  - юг: ~55.3 (граница с Казахстаном/Курганской)
#  - север: ~59.5 (граница с ХМАО)
#  - запад: ~64.4 (граница со Свердловской)
#  - восток: ~74.6 (граница с Омской/Томской)
TYUMEN_BBOX = {
    "lat_min": 55.30,
    "lat_max": 59.50,
    "lon_min": 64.40,
    "lon_max": 74.60,
}


def is_in_tyumen(lat: float, lon: float) -> bool:
    return (
        TYUMEN_BBOX["lat_min"] <= lat <= TYUMEN_BBOX["lat_max"]
        and TYUMEN_BBOX["lon_min"] <= lon <= TYUMEN_BBOX["lon_max"]
    )


def tyumen_center() -> tuple[float, float]:
    """Центр Тюменской области — для маршрутных дефолтов."""
    return 57.15, 65.55  # координаты Тюмени
